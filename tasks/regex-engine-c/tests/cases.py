"""Hidden behavioural cases for the regex engine.

Each case is (pattern, string). The EXPECTED exit code is computed by the
reference engine in expected.py, never hardcoded here, so the two can never
drift. 'match' -> 0, 'no match' -> 1, 'syntax error' -> 2.
"""

# (pattern, string) pairs. Strings never contain a newline.
CASES = [
    # --- literals ---
    ("abc", "abc"),
    ("abc", "xxabcyy"),
    ("abc", "ab"),
    ("", "anything"),
    ("z", ""),
    # --- dot ---
    ("a.c", "axc"),
    ("a.c", "ac"),
    ("...", "ab"),
    ("a.", "a\t"),
    # --- anchors ---
    ("^abc", "abcdef"),
    ("^abc", "xabc"),
    ("abc$", "zzabc"),
    ("abc$", "abcz"),
    ("^abc$", "abc"),
    ("^abc$", "abcd"),
    ("^$", ""),
    ("^$", "x"),
    # --- classes ---
    ("[abc]", "zzc"),
    ("[abc]", "zzz"),
    ("[a-z]", "9x9"),
    ("[a-z]", "999"),
    ("[^0-9]", "123a"),
    ("[^0-9]", "12345"),
    ("[]x]", "]"),
    ("[]x]", "x"),
    ("[]x]", "y"),
    ("[A-Za-z0-9]", "___k___"),
    ("[-a]", "-"),
    ("[a-]", "-"),
    # --- quantifiers ---
    ("ab*c", "ac"),
    ("ab*c", "abbbc"),
    ("ab*c", "abx"),
    ("ab+c", "ac"),
    ("ab+c", "abbc"),
    ("ab?c", "ac"),
    ("ab?c", "abc"),
    ("ab?c", "abbc"),
    ("a.*b", "axxxxb"),
    ("a.*b", "ab"),
    ("a.*b", "axxx"),
    # --- bounded repetition ---
    ("a{3}", "aa"),
    ("a{3}", "aaa"),
    ("a{3}", "aaaa"),
    ("a{2,}", "a"),
    ("a{2,}", "aaaaa"),
    ("a{2,3}", "a"),
    ("a{2,3}", "aaa"),
    ("a{2,3}", "aaaa"),
    ("(ab){2}", "abab"),
    ("(ab){2}", "aba"),
    # --- grouping + alternation ---
    ("(abc)", "abc"),
    ("a(b|c)d", "abd"),
    ("a(b|c)d", "acd"),
    ("a(b|c)d", "aed"),
    ("cat|dog", "hotdog"),
    ("cat|dog", "fish"),
    ("(cat|dog)s", "cats"),
    ("(cat|dog)s", "dogs"),
    ("(cat|dog)s", "cat"),
    ("^(a|b)+$", "abba"),
    ("^(a|b)+$", "abxa"),
    ("(foo|bar|baz)+", "barbazfoo"),
    # --- escapes ---
    (r"a\.c", "a.c"),
    (r"a\.c", "axc"),
    (r"\(", "("),
    (r"\*", "*"),
    (r"a\\b", "a\\b"),
    (r"\[", "["),
    # --- combined / harder ---
    ("^[A-Za-z][A-Za-z0-9_]*$", "var_1"),
    ("^[A-Za-z][A-Za-z0-9_]*$", "1var"),
    ("^-?[0-9]+$", "-42"),
    ("^-?[0-9]+$", "4-2"),
    (r"^[0-9]{1,3}(\.[0-9]{1,3}){3}$", "192.168.0.1"),
    (r"^[0-9]{1,3}(\.[0-9]{1,3}){3}$", "192.168.0"),
    ("(ab|a)(c|bc)", "abc"),
    ("a.*z.*q", "a__z__q"),
    ("a.*z.*q", "a__q__z"),
    ("[0-9]+(\\.[0-9]+)?", "3.14"),
    ("[0-9]+(\\.[0-9]+)?", "x"),
    # --- malformed patterns -> syntax error (exit 2) ---
    ("(", "x"),
    (")", "x"),
    ("a(b", "x"),
    ("[abc", "x"),
    ("a{", "x"),
    ("a{2,1}", "x"),
    ("*abc", "x"),
    ("a**", "x"),
    ("+", "x"),
    ("a{,}", "x"),
]
